// Writes src/crits/critKit/registry.gen.ts: every played crit (floor, income,
// button, lock and rate crits) from its folder, src/crits/<group>Crits/crits/
// <kind>/, with its meta.ts card copied in (startup reads only that) and a
// loader for its index.ts (its animation and reward, loaded when it's armed or
// plays). A crit's folder is all there is to wiring one. Run by vite (on start
// and whenever a crit folder or meta.ts changes) and by `npm run build`.
// Usage: node scripts/crit-registry.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CRITS = path.join(ROOT, "src/crits");
const OUT = path.join(CRITS, "critKit/registry.gen.ts");
export const CRIT_GROUPS = ["floor", "income", "button", "lock", "rate"];

// the card's object literal, on one line, comments dropped
function readMeta(file) {
  const text = fs.readFileSync(file, "utf8");
  const card = /export default (\{[\s\S]*?\}) satisfies CritMeta/.exec(text);
  if (!card)
    throw new Error(
      `${path.relative(ROOT, file)}: no "export default { ... } satisfies CritMeta"`,
    );
  return card[1]
    .replace(/^\s*\/\/.*$/gm, "")
    .replace(/\s+/g, " ")
    .replace(/,\s*\}$/, " }")
    .replace(/^\{\s*/, "{ ");
}

// every played crit by group: [{ kind, meta }] in kind order
export function readCrits() {
  const groups = {};
  for (const group of CRIT_GROUPS) {
    const dir = path.join(CRITS, `${group}Crits/crits`);
    groups[group] = fs
      .readdirSync(dir, { withFileTypes: true })
      .filter((entry) => entry.isDirectory())
      .map((entry) => entry.name)
      .sort()
      .map((kind) => {
        const folder = path.join(dir, kind);
        const meta = path.join(folder, "meta.ts");
        if (!fs.existsSync(meta))
          throw new Error(`${path.relative(ROOT, folder)}: no meta.ts`);
        return { kind, meta: readMeta(meta), file: meta };
      });
  }
  return groups;
}

export function writeCritRegistry() {
  const groups = readCrits();
  const lines = [
    "// generated by scripts/crit-registry.mjs from each played crit's folder",
    "// (src/crits/<group>Crits/crits/<kind>/meta.ts): don't edit",
    'import type { CritMeta } from "./meta";',
    "",
    "// every played crit's card, by group",
    "export const CRITS = {",
  ];
  for (const group of CRIT_GROUPS) {
    lines.push(`  ${group}: {`);
    for (const { kind, meta } of groups[group])
      lines.push(`    ${kind}: ${meta},`);
    lines.push("  },");
  }
  lines.push(
    "} as const satisfies Record<string, Record<string, CritMeta>>;",
    "",
    "// each played crit's module (its animation and reward)",
    "export const CRIT_LOADERS = {",
  );
  for (const group of CRIT_GROUPS)
    for (const { kind } of groups[group])
      lines.push(`  ${kind}: () => import("../${group}Crits/crits/${kind}"),`);
  lines.push("};", "");
  const source = lines.join("\n");
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (current !== source) fs.writeFileSync(OUT, source);
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
)
  writeCritRegistry();
